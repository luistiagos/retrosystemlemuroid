package com.swordfish.lemuroid.app.mobile.shared.compose.ui

import androidx.compose.foundation.background
import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.aspectRatio
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.layout.ContentScale
import androidx.compose.ui.platform.LocalContext
import coil.compose.AsyncImage
import coil.request.ImageRequest
import com.swordfish.lemuroid.app.shared.covers.CoverUtils
import com.swordfish.lemuroid.lib.library.db.entity.Game

/**
 * Game cover, 3:4. Without art (or when it fails to load) draws the [GeneratedCover].
 *
 * @param generatedCoverTitle false where the title is already printed next to the cover.
 * @param compact small thumbnail (list rows): decoded at [COMPACT_DECODE_PX] and the generated
 * cover has no title.
 */
@Composable
fun LemuroidGameImage(
    modifier: Modifier = Modifier,
    game: Game,
    generatedCoverTitle: Boolean = true,
    compact: Boolean = false,
) {
    val context = LocalContext.current
    // On weak devices decode covers smaller (less bitmap memory per item) and skip the
    // crossfade (no second bitmap held during the animation). Computed once per device.
    val lowRam = remember { CoverUtils.isLowRamDevice(context) }
    val imageRequest =
        remember(game.coverFrontUrl, lowRam, compact) {
            ImageRequest.Builder(context)
                .data(game.coverFrontUrl)
                .crossfade(!lowRam)
                .size(
                    when {
                        compact -> COMPACT_DECODE_PX
                        lowRam -> 256
                        else -> 400
                    },
                )
                .build()
        }

    // No URL, or the download failed (offline, 404, throttled by ThrottleFailedThumbnailsInterceptor):
    // draw the generated cover instead of the image. While loading, the system tone shows through.
    var showGenerated by remember(game.coverFrontUrl) { mutableStateOf(game.coverFrontUrl.isNullOrBlank()) }
    val loadingBackground =
        remember(game.systemId) {
            SystemPalette.darkTone(SystemPalette.colorForSystemId(game.systemId))
        }

    Box(
        modifier =
            modifier
                .fillMaxWidth()
                .aspectRatio(0.75f),
    ) {
        if (showGenerated) {
            GeneratedCover(
                game = game,
                modifier = Modifier.matchParentSize(),
                showTitle = generatedCoverTitle && !compact,
            )
        } else {
            AsyncImage(
                model = imageRequest,
                contentDescription = game.title,
                modifier =
                    Modifier
                        .matchParentSize()
                        .background(loadingBackground),
                onError = { showGenerated = true },
                contentScale = ContentScale.Crop,
            )
        }
    }
}

// A 56 dp row thumbnail is ~150 px on xxhdpi.
private const val COMPACT_DECODE_PX = 160
